select
  (select count(*) from diem_truong d where d.truong_id = t.id)              as diem_truong,
  (select count(*) from khung_gio k where k.truong_id = t.id and k.bat)      as buoi_hoc,
  (select count(*) from giao_vien g where g.truong_id = t.id)                as giao_vien,
  (select count(*) from lop l where l.truong_id = t.id)                      as lop,
  (select count(*) from lop l where l.truong_id = t.id and l.gvcn_id is not null) as lop_co_chu_nhiem,
  (select count(*) from phan_cong p where p.truong_id = t.id)                as dong_phan_cong,
  (select coalesce(sum(p.so_tiet),0) from phan_cong p where p.truong_id = t.id) as tong_tiet
from truong t where t.ma_truong = 'THDL';

