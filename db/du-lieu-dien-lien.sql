-- ---------- 1. Điểm trường ----------
insert into diem_truong (truong_id, ten, co_phong_tin, thu_tu)
select t.id, 'Điểm trường Diễn Liên', true, 0 from truong t
where t.ma_truong = 'THDL'
  and not exists (select 1 from diem_truong d where d.truong_id = t.id and d.ten = 'Điểm trường Diễn Liên');

